//! Deterministic Malbolge-to-C decompilation backend.

use std::fmt::{Display, Formatter, Result as FormatResult, Write as _};

use malbolge::{ProfileDescriptor, ProfileMachine, ProfileMachineError};

const INITIAL_TRANSLATION: &[u8; 94] =
    b"+b(29e*j1VMEKLyC})8&m#~W>qxdRp0wkrUo[D7,XTcA\"lI\
.v%{gJh4G\\-=O@5`_3i<?Z';FNQuY]szf$!BS/|t:Pn6^Ha";

const C_TEMPLATE: &str = r#"/* Generated by Malbolge decompiler. */
/* Profile: @PROFILE_ID@ @PROFILE_VERSION@ */
/* Fingerprint: @PROFILE_FINGERPRINT@ */
/* This is semantic C, not recovered original source. */

#include <stddef.h>
#include <stdint.h>

#define MB_WORD_MODULUS UINT32_C(@WORD_MODULUS@)
#define MB_MEMORY_WORDS UINT32_C(@MEMORY_WORDS@)
#define MB_EOF_WORD UINT32_C(@EOF_WORD@)
#define MB_WORD_TRITS UINT32_C(@WORD_TRITS@)
#define MB_GRAPHICAL_MIN UINT32_C(33)
#define MB_GRAPHICAL_MAX UINT32_C(126)
#define MB_DECODE_MODULUS UINT32_C(94)

@INITIAL_LISTING@

static const uint8_t MB_SOURCE[] = {
@SOURCE_BYTES@
};

static const uint8_t MB_TRANSLATION[] =
    "+b(29e*j1VMEKLyC})8&m#~W>qxdRp0wkrUo[D7,XTcA\"lI"
    ".v%{gJh4G\\-=O@5`_3i<?Z';FNQuY]szf$!BS/|t:Pn6^Ha";

static const uint8_t MB_ENCRYPTION[] =
    "5z]&gqtyfr$(we4{WP)H-Zn,[%\\3dL+Q;>U!pJS72FhOA1C"
    "B6v^=I_0/8|jsb9m<.TVac`uY*MK'X~xDl}REokN:#?G\"i@";

enum mb_status {
    MB_STATUS_BUDGET_EXHAUSTED = 0,
    MB_STATUS_HALT = 1,
    MB_STATUS_NON_GRAPHICAL = 2,
    MB_STATUS_INVALID_ENCRYPTION = 3,
    MB_STATUS_INVALID_ARGUMENT = 4
};

struct mb_result {
    uint32_t accumulator;
    uint32_t code_pointer;
    uint32_t data_pointer;
    size_t input_consumed;
    size_t output_len;
    size_t steps;
    enum mb_status status;
};

static uint32_t mb_successor(uint32_t value)
{
    return value + UINT32_C(1) == MB_WORD_MODULUS
        ? UINT32_C(0)
        : value + UINT32_C(1);
}

static uint32_t mb_rotate(uint32_t value)
{
    const uint32_t low_trit = value % UINT32_C(3);
    return value / UINT32_C(3)
        + low_trit * (MB_WORD_MODULUS / UINT32_C(3));
}

static uint32_t mb_crazy(uint32_t data, uint32_t accumulator)
{
    static const uint8_t table[3][3] = {
        {1, 0, 0},
        {1, 0, 2},
        {2, 2, 1}
    };
    uint32_t result = UINT32_C(0);
    uint32_t place = UINT32_C(1);
    uint32_t trit = UINT32_C(0);
    while (trit < MB_WORD_TRITS) {
        const uint32_t data_trit = data % UINT32_C(3);
        const uint32_t accumulator_trit = accumulator % UINT32_C(3);
        result += (uint32_t)table[data_trit][accumulator_trit] * place;
        place *= UINT32_C(3);
        data /= UINT32_C(3);
        accumulator /= UINT32_C(3);
        ++trit;
    }
    return result;
}

static int mb_graphical(uint32_t value)
{
    return value >= MB_GRAPHICAL_MIN && value <= MB_GRAPHICAL_MAX;
}

static uint32_t mb_encrypted(uint32_t value)
{
    return (uint32_t)MB_ENCRYPTION[value - MB_GRAPHICAL_MIN];
}

uint32_t malbolge_decompiled_memory_words(void)
{
    return MB_MEMORY_WORDS;
}

int malbolge_decompiled_run(
    uint32_t *memory,
    size_t memory_words,
    const uint8_t *input,
    size_t input_len,
    uint8_t *output,
    size_t output_capacity,
    size_t step_budget,
    struct mb_result *result)
{
    const size_t source_len = sizeof(MB_SOURCE) / sizeof(MB_SOURCE[0]);
    uint32_t accumulator = UINT32_C(0);
    uint32_t code_pointer = UINT32_C(0);
    uint32_t data_pointer = UINT32_C(0);
    size_t input_cursor = 0;
    size_t output_len = 0;
    size_t steps = 0;
    enum mb_status status = MB_STATUS_BUDGET_EXHAUSTED;
    size_t index = 0;

    if (result != NULL) {
        result->accumulator = UINT32_C(0);
        result->code_pointer = UINT32_C(0);
        result->data_pointer = UINT32_C(0);
        result->input_consumed = 0;
        result->output_len = 0;
        result->steps = 0;
        result->status = MB_STATUS_INVALID_ARGUMENT;
    }
    if (memory == NULL || result == NULL
        || memory_words != (size_t)MB_MEMORY_WORDS
        || (input_len != 0 && input == NULL)
        || output_capacity < step_budget
        || (step_budget != 0 && output == NULL)) {
        return (int)MB_STATUS_INVALID_ARGUMENT;
    }

    for (index = 0; index < source_len; ++index) {
        memory[index] = (uint32_t)MB_SOURCE[index];
    }
    for (index = source_len; index < memory_words; ++index) {
        memory[index] = mb_crazy(memory[index - 2], memory[index - 1]);
    }

    while (steps < step_budget) {
        const uint32_t cell = memory[code_pointer];
        uint32_t next_accumulator = accumulator;
        uint32_t next_code_pointer = code_pointer;
        uint32_t next_data_pointer = data_pointer;
        uint32_t write_address = UINT32_C(0);
        uint32_t write_value = UINT32_C(0);
        uint32_t encryption_target = UINT32_C(0);
        uint32_t encrypted = UINT32_C(0);
        uint8_t output_byte = UINT8_C(0);
        int consumes_input = 0;
        int emits_output = 0;
        int writes_memory = 0;
        uint32_t decoded = UINT32_C(0);

        if (!mb_graphical(cell)) {
            ++steps;
            status = MB_STATUS_NON_GRAPHICAL;
            break;
        }
        decoded = (uint32_t)MB_TRANSLATION[
            (cell - MB_GRAPHICAL_MIN
                + (code_pointer % MB_DECODE_MODULUS))
            % MB_DECODE_MODULUS
        ];
        if (decoded == (uint32_t)'v') {
            ++steps;
            status = MB_STATUS_HALT;
            break;
        }

        switch (decoded) {
        case 'i':
            next_code_pointer = memory[data_pointer];
            break;
        case '/':
            output_byte = (uint8_t)(accumulator % UINT32_C(256));
            emits_output = 1;
            break;
        case '<':
            consumes_input = 1;
            break;
        case '*':
            write_address = data_pointer;
            write_value = mb_rotate(memory[data_pointer]);
            next_accumulator = write_value;
            writes_memory = 1;
            break;
        case 'j':
            next_data_pointer = memory[data_pointer];
            break;
        case 'p':
            write_address = data_pointer;
            write_value = mb_crazy(memory[data_pointer], accumulator);
            next_accumulator = write_value;
            writes_memory = 1;
            break;
        case 'o':
        default:
            break;
        }

        encryption_target = writes_memory
            && write_address == next_code_pointer
            ? write_value
            : memory[next_code_pointer];
        if (!mb_graphical(encryption_target)) {
            status = MB_STATUS_INVALID_ENCRYPTION;
            break;
        }
        encrypted = mb_encrypted(encryption_target);

        if (consumes_input) {
            if (input_cursor < input_len) {
                next_accumulator = (uint32_t)input[input_cursor];
                ++input_cursor;
            } else {
                next_accumulator = MB_EOF_WORD;
            }
        }
        if (writes_memory && write_address != next_code_pointer) {
            memory[write_address] = write_value;
        }
        memory[next_code_pointer] = encrypted;
        accumulator = next_accumulator;
        code_pointer = mb_successor(next_code_pointer);
        data_pointer = mb_successor(next_data_pointer);
        if (emits_output) {
            output[output_len] = output_byte;
            ++output_len;
        }
        ++steps;
    }

    result->accumulator = accumulator;
    result->code_pointer = code_pointer;
    result->data_pointer = data_pointer;
    result->input_consumed = input_cursor;
    result->output_len = output_len;
    result->steps = steps;
    result->status = status;
    return (int)status;
}
"#;

/// Deterministic decompilation failure.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DecompileError {
    /// Input source is invalid for the explicitly selected profile.
    InvalidSource(ProfileMachineError),
    /// Validated source position unexpectedly cannot fit the profile address
    /// type.
    PositionOverflow,
    /// Rendering into the owned String unexpectedly reported formatting
    /// failure.
    Rendering,
}

impl Display for DecompileError {
    fn fmt(&self, f: &mut Formatter<'_>) -> FormatResult {
        match self {
            Self::InvalidSource(error) => write!(f, "invalid source: {error}"),
            Self::PositionOverflow => f.write_str("source position overflow"),
            Self::Rendering => f.write_str("C rendering failed"),
        }
    }
}

/// Renders one validated Malbolge source as readable executable C23.
///
/// The output is a semantics-preserving specialized machine, not a claim that
/// the original human-authored C source can be reconstructed from Malbolge.
///
/// # Errors
///
/// Returns [`DecompileError::InvalidSource`] when `source` is not admitted by
/// `profile`, [`DecompileError::PositionOverflow`] on impossible position
/// conversion failure after validation, or [`DecompileError::Rendering`] if the
/// owned output buffer unexpectedly rejects formatting.
pub fn render_c(
    profile: &'static ProfileDescriptor,
    source: &[u8],
) -> Result<String, DecompileError> {
    let _validated = ProfileMachine::from_source(profile, source, Vec::new())
        .map_err(DecompileError::InvalidSource)?;
    let admitted = source
        .iter()
        .copied()
        .filter(|byte| !byte.is_ascii_whitespace())
        .collect::<Vec<_>>();
    let listing = initial_listing(&admitted)?;
    let bytes = source_bytes(&admitted)?;
    Ok(C_TEMPLATE
        .replace("@PROFILE_ID@", profile.id())
        .replace("@PROFILE_VERSION@", profile.version())
        .replace("@PROFILE_FINGERPRINT@", profile.fingerprint())
        .replace("@WORD_MODULUS@", &profile.word_modulus().to_string())
        .replace("@MEMORY_WORDS@", &profile.memory_words().to_string())
        .replace("@EOF_WORD@", &profile.eof_word().to_string())
        .replace("@WORD_TRITS@", &profile.word_trits().to_string())
        .replace("@INITIAL_LISTING@", &listing)
        .replace("@SOURCE_BYTES@", &bytes))
}

fn initial_listing(source: &[u8]) -> Result<String, DecompileError> {
    let mut output = String::from("/* Initial normalized decode:\n");
    for (position, byte) in source.iter().copied().enumerate() {
        let phase = position.rem_euclid(INITIAL_TRANSLATION.len());
        let cell_offset = usize::from(byte.saturating_sub(33));
        let translation = cell_offset
            .saturating_add(phase)
            .rem_euclid(INITIAL_TRANSLATION.len());
        let decoded = INITIAL_TRANSLATION
            .get(translation)
            .copied()
            .ok_or(DecompileError::PositionOverflow)?;
        let name = decoded_name(decoded);
        writeln!(&mut output, " * {position:>8}: {byte:>3} -> {name}")
            .map_err(|_error| DecompileError::Rendering)?;
    }
    output.push_str(" */");
    Ok(output)
}

const fn decoded_name(decoded: u8) -> &'static str {
    match decoded {
        b'i' => "i  jump code pointer from [D]",
        b'/' => "/  output low byte of A",
        b'<' => "<  input byte into A",
        b'*' => "*  rotate [D] into A and [D]",
        b'j' => "j  load D from [D]",
        b'p' => "p  crazy [D], A into A and [D]",
        b'o' => "o  no-op",
        b'v' => "v  halt",
        _ => "?  invalid initial instruction",
    }
}

fn source_bytes(source: &[u8]) -> Result<String, DecompileError> {
    let mut output = String::new();
    let mut chunks = source.chunks(12).peekable();
    while let Some(chunk) = chunks.next() {
        output.push_str("    ");
        let mut bytes = chunk.iter().copied().peekable();
        while let Some(byte) = bytes.next() {
            write!(&mut output, "UINT8_C({byte})")
                .map_err(|_error| DecompileError::Rendering)?;
            if bytes.peek().is_some() || chunks.peek().is_some() {
                output.push_str(", ");
            }
        }
        output.push('\n');
    }
    Ok(output)
}
