fn span(begin: u32, end: u32, line: u32, line_begin: u32) -> Value {
    json!({"begin":{"byte":begin,"line":line,"column":begin.saturating_sub(line_begin).saturating_add(1)},
           "end":{"byte":end,"line":line,"column":end.saturating_sub(line_begin).saturating_add(1)}})
}

fn input() -> Value {
    // Generated by actual pinned Clang 22.1.8 for the exact source below.
    // The source starts with `#include <stdio.h>\n` (19 bytes).
    let source_span = |begin, end| span(begin, end, 2, 19);
    json!({
        "schema_version": 1,
        "artifact_id": "malbolge-c-frontend-v1",
        "clang": {"version":"22.1.8", "target":"wasm32-unknown-unknown", "language":"c23"},
        "profile": {"abi_id":"malbolge-c32-v1", "target_profile":"malbolge-2026"},
        "source": {"id":"fixtures/output.c", "sha256":
            "a89c18405bc20022ede681f378721e9ba71298fd250b2841417bfe1a01a43009"},
        "nodes": [
            {"id":1,"parent":0,"kind":"function-declaration","span":source_span(19,58),
             "name":"emit","type":"fn()->void","definition":"definition",
             "inline_specified":false,"linkage":"external","storage_class":"none"},
            {"id":2,"parent":1,"kind":"compound-statement","span":source_span(35,58)},
            {"id":3,"parent":2,"kind":"call-expression","span":source_span(37,47),
             "type":"i32","reference":"external:putchar"},
            {"id":4,"parent":3,"kind":"cast-expression","span":source_span(37,44),
             "type":"ptr(fn(i32)->i32)","operation":"function-to-pointer"},
            {"id":5,"parent":4,"kind":"declaration-reference-expression",
             "span":source_span(37,44),"type":"fn(i32)->i32","reference":"external:putchar"},
            {"id":6,"parent":3,"kind":"integer-literal","span":source_span(45,46),
             "type":"i32","constant_integer":"0","literal":"0"},
            {"id":7,"parent":2,"kind":"return-statement","span":source_span(49,55)}
        ]
    })
}

#[expect(
    clippy::expect_used,
    reason = "test-only JSON serializes deterministically"
)]
fn bytes(source: &Value) -> Vec<u8> {
    serde_json::to_vec(source).expect("test JSON serializes")
}

#[test]
#[expect(
    clippy::cognitive_complexity,
    clippy::panic_in_result_fn,
    reason = "real guest evidence requires exact VM assertions"
)]
fn putchar_zero_compiles_through_canonical_typed_and_real_guest() -> Result<(), String> {
    let source = input();
    assert!(canonical_void_typed_ir(&bytes(&source)).is_err());
    let (wire, mode) = canonical_guest_typed_ir(&bytes(&source))
        .map_err(|error| format!("C output lowering: {error:?}"))?;
    assert_eq!(mode, FrontendGuestMode::InitialZeroOutput);
    let module =
        typed::canonical_module(&wire).map_err(|error| format!("decode MCTI: {error:?}"))?;
    let effects = module
        .functions()
        .first()
        .and_then(|function| function.blocks().first())
        .ok_or("missing typed function block")?
        .instructions();
    assert!(matches!(
        effects,
        [first, second] if matches!(first.instruction(), typed::Instruction::ConstantInteger { .. })
            && matches!(second.instruction(), typed::Instruction::ByteOutput { .. })
    ));
    assert_eq!(module.source_id(), "fixtures/output.c");
    let profile = target_profile("malbolge-2026").ok_or("missing current profile")?;
    let compiled = compile_canonical_typed_initial_zero_outputs(&wire, profile)
        .map_err(|error| format!("MCTI to Malbolge: {error:?}"))?;
    let mut vm = ProfileMachine::from_source(profile, compiled.layout().source(), Vec::new())
        .map_err(|error| format!("load guest: {error:?}"))?;
    assert!(matches!(
        vm.run(2),
        Ok(RunOutcome::Terminated { steps: 2, .. })
    ));
    assert_eq!(vm.output(), &[0]);
    Ok(())
}

#[test]
#[expect(
    clippy::indexing_slicing,
    clippy::default_numeric_fallback,
    clippy::shadow_unrelated,
    clippy::unwrap_used,
    reason = "synthetic fixed-size JSON mutation examples"
)]
fn forged_output_call_and_metadata_do_not_compile() {
    let base = input();
    let mut mutations = Vec::new();
    let mut changed = base.clone();
    changed["nodes"][2]["reference"] = json!("external:getchar");
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][4]["reference"] = json!("external:puts");
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][3]["operation"] = json!("lvalue-to-rvalue");
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][5]["literal"] = json!("1");
    changed["nodes"][5]["constant_integer"] = json!("1");
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][5]["parent"] = json!(2);
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][3]["parent"] = json!(2);
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][2]["span"]["end"]["byte"] = json!(46);
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][6]["kind"] = json!("call-expression");
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][5]["extra"] = json!("ignored");
    mutations.push(changed);
    let mut changed = base.clone();
    changed["nodes"][0]["type"] = json!("fn()->i32");
    mutations.push(changed);
    let mut changed = base;
    changed["nodes"].as_array_mut().unwrap().push(json!({
        "id":8,"parent":2,"kind":"call-expression","span":span(55,56,2,19)
    }));
    mutations.push(changed);
    for (index, candidate) in mutations.iter().enumerate() {
        assert!(
            canonical_guest_typed_ir(&bytes(candidate)).is_err(),
            "mutant {index}"
        );
    }
}

#[test]
#[expect(
    clippy::indexing_slicing,
    clippy::default_numeric_fallback,
    clippy::panic_in_result_fn,
    reason = "fixed native AST fixture and result-returning real compiler test"
)]
fn unsupported_no_effect_void_still_uses_original_guest_mode() -> Result<(), String> {
    let mut source = input();
    source["nodes"] = json!([
        source["nodes"][0].clone(),
        source["nodes"][1].clone(),
        source["nodes"][6].clone()
    ]);
    source["nodes"][2]["id"] = json!(3);
    let (_, mode) = canonical_guest_typed_ir(&bytes(&source))
        .map_err(|error| format!("original empty-void path: {error:?}"))?;
    assert_eq!(mode, FrontendGuestMode::EmptyVoid);
    Ok(())
}
