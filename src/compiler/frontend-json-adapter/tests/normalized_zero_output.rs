fn span(begin: u32, end: u32, line: u32, line_begin: u32) -> Value {
    json!({"begin":{"byte":begin,"line":line,"column":begin.saturating_sub(line_begin).saturating_add(1)},
           "end":{"byte":end,"line":line,"column":end.saturating_sub(line_begin).saturating_add(1)}})
}

fn input() -> Value {
    // Generated by actual pinned Clang 22.1.8 for the exact source below.
    // The source starts with `#include <stdio.h>\n` (19 bytes).
    let source_span = |begin, end| span(begin, end, 2, 19);
    json!({
        "schema_version": 1,
        "artifact_id": "malbolge-c-frontend-v1",
        "clang": {"version":"22.1.8", "target":"wasm32-unknown-unknown", "language":"c23"},
        "profile": {"abi_id":"malbolge-c32-v1", "target_profile":"malbolge-2026"},
        "source": {"id":"fixtures/output.c", "sha256":
            "a89c18405bc20022ede681f378721e9ba71298fd250b2841417bfe1a01a43009"},
        "nodes": [
            {"id":1,"parent":0,"kind":"function-declaration","span":source_span(19,58),
             "name":"emit","type":"fn()->void","definition":"definition",
             "inline_specified":false,"linkage":"external","storage_class":"none"},
            {"id":2,"parent":1,"kind":"compound-statement","span":source_span(35,58)},
            {"id":3,"parent":2,"kind":"call-expression","span":source_span(37,47),
             "type":"i32","reference":"external:putchar"},
            {"id":4,"parent":3,"kind":"cast-expression","span":source_span(37,44),
             "type":"ptr(fn(i32)->i32)","operation":"function-to-pointer"},
            {"id":5,"parent":4,"kind":"declaration-reference-expression",
             "span":source_span(37,44),"type":"fn(i32)->i32","reference":"external:putchar"},
            {"id":6,"parent":3,"kind":"integer-literal","span":source_span(45,46),
             "type":"i32","constant_integer":"0","literal":"0"},
            {"id":7,"parent":2,"kind":"return-statement","span":source_span(49,55)}
        ]
    })
}

// Exact pinned-Clang preorder is four children per direct output call.
// Source spelling and normalized decimal value are independent for characters.
fn repeated_literal_input(byte: u8, outputs: u32) -> Value {
    let width = u32::try_from(byte.to_string().len()).unwrap_or_default();
    repeated_output_input(byte, outputs, "integer-literal", width)
}

fn repeated_character_input(byte: u8, outputs: u32, width: u32) -> Value {
    repeated_output_input(byte, outputs, "character-literal", width)
}

#[expect(
    clippy::arithmetic_side_effects,
    clippy::indexing_slicing,
    clippy::shadow_unrelated,
    clippy::default_numeric_fallback,
    reason = "closed synthetic Clang fixture spans for at most 34 bounded calls"
)]
fn repeated_output_input(byte: u8, outputs: u32, kind: &str, width: u32) -> Value {
    let mut source = input();
    let literal = byte.to_string();
    let call_width = 9 + width;
    let total_extra = outputs.saturating_mul(width.saturating_sub(1))
        + outputs.saturating_sub(1).saturating_mul(12);
    let end = 58 + total_extra;
    source["nodes"][0]["span"] = span(19, end, 2, 19);
    source["nodes"][1]["span"] = span(35, end, 2, 19);
    let source_span = |begin, end| span(begin, end, 2, 19);
    let mut nodes = vec![source["nodes"][0].clone(), source["nodes"][1].clone()];
    for index in 0..outputs {
        let begin = 37 + index * (call_width + 2);
        let id = 3 + index * 4;
        nodes.push(json!({
            "id":id,"parent":2,"kind":"call-expression",
            "span":source_span(begin,begin+call_width),
            "type":"i32","reference":"external:putchar"
        }));
        nodes.push(json!({
            "id":id+1,"parent":id,"kind":"cast-expression",
            "span":source_span(begin,begin+7),
            "type":"ptr(fn(i32)->i32)","operation":"function-to-pointer"
        }));
        nodes.push(json!({
            "id":id+2,"parent":id+1,"kind":"declaration-reference-expression",
            "span":source_span(begin,begin+7),"type":"fn(i32)->i32","reference":"external:putchar"
        }));
        nodes.push(json!({
            "id":id+3,"parent":id,"kind":kind,
            "span":source_span(begin+8,begin+8+width),
            "type":"i32","constant_integer":literal,"literal":literal
        }));
    }
    nodes.push(json!({
        "id":3+outputs*4,"parent":2,"kind":"return-statement",
        "span":source_span(49+total_extra,55+total_extra)
    }));
    source["nodes"] = json!(nodes);
    source
}

fn repeated_input(outputs: u32) -> Value {
    repeated_literal_input(0, outputs)
}

#[test]
#[expect(
    clippy::panic_in_result_fn,
    clippy::cognitive_complexity,
    reason = "bounded 1-to-33 caller traces with exact VM output counts"
)]
fn repeated_zero_calls_preserve_source_and_emit_order() -> Result<(), String> {
    let profile = target_profile("malbolge-2026").ok_or("missing current profile")?;
    for outputs in [2u32, 3, 32, 33] {
        let source = repeated_input(outputs);
        let output_count = usize::try_from(outputs).map_err(|error| error.to_string())?;
        let (wire, mode) = canonical_guest_typed_ir(&bytes(&source))
            .map_err(|error| format!("{outputs} C outputs: {error:?}"))?;
        assert_eq!(mode, FrontendGuestMode::InitialZeroOutput);
        let module =
            typed::canonical_module(&wire).map_err(|error| format!("decode MCTI: {error:?}"))?;
        let effects = module
            .functions()
            .first()
            .and_then(|function| function.blocks().first())
            .ok_or("missing typed block")?
            .instructions();
        assert_eq!(effects.len(), output_count + 1);
        assert!(matches!(
            effects.first().map(typed::LocatedInstruction::instruction),
            Some(typed::Instruction::ConstantInteger { .. })
        ));
        assert!(
            effects.iter().skip(1).all(|effect| matches!(
                effect.instruction(),
                typed::Instruction::ByteOutput { .. }
            ))
        );
        let compiled = compile_canonical_typed_initial_zero_outputs(&wire, profile)
            .map_err(|error| format!("compile guest: {error:?}"))?;
        let mut vm = ProfileMachine::from_source(profile, compiled.layout().source(), Vec::new())
            .map_err(|error| format!("load guest: {error:?}"))?;
        assert!(matches!(
            vm.run(output_count + 1),
            Ok(RunOutcome::Terminated { steps, .. }) if steps == output_count + 1
        ));
        assert_eq!(vm.output(), vec![0; output_count]);
    }
    Ok(())
}

#[test]
fn source_ordered_literal_ssa_preserves_repeated_and_changed_bytes()
-> Result<(), String> {
    // Distinct guest layouts are not inferred from this frontend projection.
    // The source-backed byte effects must preserve both SSA identity and order.
    for (expected, definitions, uses, mode) in [
        (
            [65u8, 65, 65],
            vec![(0u32, 65u8)],
            vec![0u32, 0, 0],
            FrontendGuestMode::SeededByteLiteral,
        ),
        (
            [65u8, 66, 67],
            vec![(0u32, 65u8), (1, 66), (2, 67)],
            vec![0u32, 1, 2],
            FrontendGuestMode::DistinctLiteralTriple,
        ),
        (
            [65u8, 65, 66],
            vec![(0u32, 65u8), (1, 66)],
            vec![0u32, 0, 1],
            FrontendGuestMode::DistinctLiteralTriple,
        ),
    ] {
        let mut source = repeated_literal_input(65, 3);
        let nodes = source
            .get_mut("nodes")
            .and_then(Value::as_array_mut)
            .ok_or("missing normalized Clang nodes")?;
        for (position, value) in [5usize, 9, 13].into_iter().zip(expected) {
            let literal = nodes.get_mut(position).ok_or("missing C literal")?;
            literal["literal"] = json!(value.to_string());
            literal["constant_integer"] = json!(value.to_string());
        }
        let (wire, observed_mode) =
            canonical_guest_typed_ir(&bytes(&source))
                .map_err(|error| format!("{expected:?}: {error:?}"))?;
        assert_eq!(observed_mode, mode);
        let module = typed::canonical_module(&wire)
            .map_err(|error| format!("canonical typed IR: {error:?}"))?;
        let instructions = module
            .functions()
            .first()
            .and_then(|function| function.blocks().first())
            .ok_or("missing source-proven function")?
            .instructions();
        let mut observed_definitions = Vec::new();
        let mut observed_uses = Vec::new();
        for instruction in instructions {
            match instruction.instruction() {
                typed::Instruction::ConstantInteger {
                    constant,
                    result,
                    ..
                } => {
                    let value = constant
                        .little_endian()
                        .first()
                        .copied()
                        .ok_or("missing byte constant")?;
                    assert_eq!(constant.bit_width(), 8);
                    observed_definitions.push((result.value(), value));
                },
                typed::Instruction::ByteOutput { value } => {
                    observed_uses.push(value.value());
                },
                other => {
                    return Err(format!("unexpected source effect: {other:?}"));
                },
            }
        }
        assert_eq!(observed_definitions, definitions);
        assert_eq!(observed_uses, uses);
    }
    Ok(())
}

