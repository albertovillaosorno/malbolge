    assert!(
        paren["nodes"][5]
            .as_object_mut()
            .is_some_and(|node| node.remove("constant_integer").is_some()),
        "wrapper fixture must contain Clang-evaluated constant"
    );
    mutations.push(paren);
    let mut paren = wrapped_zero_input(true);
